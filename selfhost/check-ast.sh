#!/bin/sh
#
# check-ast.sh - Phase 9.1–9.4b: the AST compiler's behavioural gate.
#
# Builds the bootstrap chain (L0 -> L1 -> L2), then builds the AST compiler
# (selfhost/ast/main.ct, D30: a separate tree in parallel with the old
# pipeline), and runs every fixture under test/ast/*/:
#
#   prog.ct -> ct-ast -> <name>.c + <name>.h -> cc (warning-free) -> run
#           -> compare stdout with prog.expected.out
#
# D34 defines equivalence as exit status + a warning-free build + identical
# program output; diagnostics and warnings are not compared. The negative
# fixture under test/ast/errors/ must exit non-zero.
#
# Usage:  bash selfhost/check-ast.sh
#         CC=gcc bash selfhost/check-ast.sh
#
# Exit code 0 means every assertion passed.

set -u

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root" || exit 1

CC="${CC:-cc}"
work="${TMPDIR:-/tmp}"
work="${work%/}/ct-ast-test.$$"

rm -rf "$work"
mkdir -p "$work" || exit 1

pass=0
fail=0
ok()  { pass=$((pass + 1)); printf '  ok    %s\n' "$1"; }
bad() { fail=$((fail + 1)); printf '  FAIL  %s: %s\n' "$1" "$2"; }

echo "cc: $CC"
echo
echo "== build the bootstrap chain and the AST compiler =="
if ! "$CC" -Wall -Wextra -std=c99 ctc.c -o "$work/ctc" 2>"$work/l0.log"; then
    echo "  compiler build failed:"; sed 's/^/    /' "$work/l0.log"; exit 1
fi
if ! "$work/ctc" selfhost/ctc.ct -o "$work/l1.c" 2>"$work/l1.log"; then
    echo "  L0 could not compile L1:"; sed 's/^/    /' "$work/l1.log"; exit 1
fi
if ! "$CC" -Wall -Wextra -std=c99 "$work/l1.c" -o "$work/l1" 2>"$work/l1b.log"; then
    echo "  L1 did not build:"; sed 's/^/    /' "$work/l1b.log"; exit 1
fi
mkdir -p "$work/l2src"
if ! "$work/l1" build selfhost/src/driver.ct -o "$work/l2src" >"$work/l2.out" 2>&1; then
    echo "  L1 could not build the split tree:"; sed 's/^/    /' "$work/l2.out"; exit 1
fi
if ! "$CC" -Wall -Wextra -std=c99 "$work/l2src"/*.c -o "$work/l2" 2>"$work/l2b.log"; then
    echo "  L2 did not build:"; sed 's/^/    /' "$work/l2b.log"; exit 1
fi
mkdir -p "$work/astsrc"
if ! "$work/l2" build selfhost/ast/main.ct -o "$work/astsrc" >"$work/ast.out" 2>&1; then
    echo "  L2 could not build the AST compiler:"; sed 's/^/    /' "$work/ast.out"; exit 1
fi
if ! "$CC" -Wall -Wextra -std=c99 "$work/astsrc"/*.c -o "$work/ct-ast" 2>"$work/astb.log"; then
    echo "  the AST compiler did not build:"; sed 's/^/    /' "$work/astb.log"; exit 1
fi
ok "the chain builds (L0 -> L1 -> L2 -> ct-ast)"

echo
echo "== behavioural cases (compile -> cc -> run -> compare) =="
for d in test/ast/*/; do
    [ -d "$d" ] || continue
    d="${d%/}"
    name="$(basename "$d")"
    src="$d/prog.ct"
    [ -f "$src" ] || continue
    out="$work/$name.c"
    exe="$work/$name.bin"

    if ! "$work/ct-ast" "$src" -o "$out" >"$work/$name.out" 2>"$work/$name.err"; then
        bad "$name" "ct-ast failed: $(cat "$work/$name.err")"
        continue
    fi
    if [ ! -f "$work/$name.h" ]; then
        bad "$name" "no header was emitted"
        continue
    fi
    if ! grep -q "Generated by ct v" "$out"; then
        bad "$name" "the banner is missing"
        continue
    fi
    if ! "$CC" -Wall -Wextra -std=c99 "$out" -o "$exe" 2>"$work/$name.cc"; then
        bad "$name" "generated C did not build warning-free: $(cat "$work/$name.cc")"
        continue
    fi
    if ! "$exe" >"$work/$name.stdout" 2>&1; then
        bad "$name" "the program exited non-zero"
        continue
    fi
    if ! cmp -s "$work/$name.stdout" "$d/prog.expected.out"; then
        bad "$name" "program output differs: $(cat "$work/$name.stdout")"
        continue
    fi
    ok "$name"
done

echo
echo "== corpus cases =="
if "$work/ct-ast" test/cases/03_passthrough.ct -o "$work/p03.c" \
        >"$work/p03.out" 2>"$work/p03.err" \
   && "$CC" -Wall -Wextra -std=c99 -c "$work/p03.c" -o "$work/p03.o" 2>"$work/p03.cc"; then
    ok "03_passthrough (struct/pointer/array shapes, compile only)"
else
    bad "03_passthrough" "$(cat "$work/p03.err" "$work/p03.cc")"
fi
if "$work/ct-ast" test/cases/01_trait_basic.ct -o "$work/p01.c" \
        >"$work/p01.out" 2>"$work/p01.err" \
   && "$CC" -Wall -Wextra -std=c99 "$work/p01.c" -o "$work/p01.bin" 2>"$work/p01.cc" \
   && "$work/p01.bin" >"$work/p01.stdout" 2>&1 \
   && cmp -s "$work/p01.stdout" test/cases/01_trait_basic.expected.out; then
    ok "01_trait_basic (trait/impl dispatch, full behaviour)"
else
    bad "01_trait_basic" "$(cat "$work/p01.err" "$work/p01.cc" "$work/p01.stdout")"
fi
for c in 18_polymorphism 21_empty_init_iface; do
    if "$work/ct-ast" "test/cases/$c.ct" -o "$work/$c.c" \
            >"$work/$c.out" 2>"$work/$c.err" \
       && "$CC" -Wall -Wextra -std=c99 "$work/$c.c" -o "$work/$c.bin" 2>"$work/$c.cc" \
       && "$work/$c.bin" >"$work/$c.stdout" 2>&1 \
       && cmp -s "$work/$c.stdout" "test/cases/$c.expected.out"; then
        ok "$c (interface values, full behaviour)"
    else
        bad "$c" "$(cat "$work/$c.err" "$work/$c.cc" "$work/$c.stdout")"
    fi
done

echo
echo "== negative case =="
if "$work/ct-ast" test/ast/errors/missing_semi.ct -o "$work/bad.c" \
        >"$work/bad.out" 2>"$work/bad.err"; then
    bad "missing_semi" "expected a non-zero exit"
elif grep -q "^ct-ast: " "$work/bad.err"; then
    ok "missing_semi (rejected with a diagnostic)"
else
    bad "missing_semi" "no diagnostic on stderr"
fi

echo
echo "== summary: $pass passed, $fail failed =="
rm -rf "$work"
[ "$fail" -eq 0 ]
