#!/bin/sh
#
# fsm-state.sh -- the `fsm/state` dialect plugin (Phase 12.3 demo).
#
# A second dialect in the SAME file as `register/map`: plugins only act on
# their own marker and pass every foreign block through untouched, so the
# driver applies them one after another (see bindings of docs/design/dialect.md
# and the authoring guide there).
#
# Usage:  sh ct-dialects/fsm-state.sh <input.ct> > <expanded.ct>
#
# Input DSL, one transition per line:
#   //@ct-dialect: fsm/state
#   //@ state <FROM> <EVENT> <TO>
#
# It emits the state / event constants and a `fsm_step(state, ev)` function.
#
# License: MIT; see LICENSE.EXCEPTION (free to copy into your own project)
set -u

if [ "$#" -ne 1 ]; then
    echo "usage: $0 <input.ct>" >&2
    exit 2
fi

awk '
function sid(x,   i) {
    for (i = 1; i <= ns; i++) if (sname[i] == x) return sidx[i]
    ns++; sname[ns] = x; sidx[ns] = ns - 1
    return sidx[ns]
}
function eid(x,   i) {
    for (i = 1; i <= ne; i++) if (ename[i] == x) return eidx[i]
    ne++; ename[ne] = x; eidx[ne] = ne
    return eidx[ne]
}
function emit(   i) {
    print "//@gen-begin -- generated by ct-dialects/fsm-state.sh, do not edit"
    for (i = 1; i <= n; i++) { sid(from[i]); sid(to[i]); eid(ev[i]) }
    for (i = 1; i <= ns; i++) printf "#define FSM_%s %d\n", toupper(sname[i]), sidx[i]
    for (i = 1; i <= ne; i++) printf "#define FSM_EV_%s %d\n", toupper(ename[i]), eidx[i]
    print "int fsm_step(int state, int ev)"
    print "{"
    for (i = 1; i <= n; i++)
        printf "    if (state == FSM_%s && ev == FSM_EV_%s) return FSM_%s;\n",
               toupper(from[i]), toupper(ev[i]), toupper(to[i])
    print "    return state;"
    print "}"
    print "//@gen-end"
}
/^\/\/@ct-dialect:/        { if (blk) { emit(); blk = 0 }
                             mine = ($2 == "fsm/state"); print; next }
mine && /^\/\/@ state /    { blk = 1; print; n++; from[n] = $3; ev[n] = $4; to[n] = $5; next }
{
    if (blk) { emit(); blk = 0 }
    print; next
}
END { if (blk) emit() }
' "$1"
